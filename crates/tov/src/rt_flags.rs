//! How the runtime is compiled: the C compiler, its flags, and the runtime's one translation unit.
//! Shared by `tov build` (src/build.rs) and the cargo build script, which compiles the runtime with
//! the default flags once and embeds the object, so a machine's first build doesn't spend seconds
//! on it (as Rust ships its standard library compiled). Both compute the same cache key from these.

use std::path::Path;
use std::process::Command;

/// The flags every C file of a program is compiled with (before TOV_CFLAGS): `opt` (`-O3`, `-Os`,
/// ...), integer overflow unchecked, debug symbols, the macOS SDK.
pub fn base_flags(opt: &str, unchecked: bool, symbols: bool, sanitize: bool, sysroot: Option<&str>) -> Vec<String> {
    // No FMA contraction: `a * b + c` rounds twice, exactly as in JavaScript (and it's faster on
    // latency-bound loops, where a fused multiply-add lengthens the dependency chain).
    let mut flags: Vec<String> = vec![opt.into(), "-std=gnu11".into(), "-w".into(), "-ffp-contract=off".into()];
    // Nothing reads errno after Math.sqrt: without the flag a square root is the instruction and
    // a branch to libm's for a negative operand (to set errno), which also keeps it out of
    // vectorized loops.
    flags.push("-fno-math-errno".into());
    // Tov code is bounds-checked, so C's stack canaries and fortified memcpy only add checks
    // (and imports: each costs about 50 bytes of binary).
    flags.extend(["-fno-stack-protector", "-U_FORTIFY_SOURCE", "-D_FORTIFY_SOURCE=0"].map(String::from));
    // Every loop starts on a 16-byte boundary: where one happens to fall otherwise swings a hot
    // loop's speed by up to 20% (spectral_norm, fannkuch) from one build to the next.
    if opt != "-Os" {
        flags.push("-falign-loops=16".into());
    }
    // Apple's clang outlines repeated instruction sequences into shared functions by default on
    // arm64: smaller code, but a hot loop then calls out for pieces of itself (JSON parsing ran
    // a third slower). Xcode's clang is the only compiler there, so the flag is known.
    if cfg!(target_vendor = "apple") && cfg!(target_arch = "aarch64") && opt != "-Os" {
        flags.push("-mno-outline".into());
    }
    if unchecked {
        flags.push("-DTOV_UNCHECKED=1".into());
    }
    if symbols {
        flags.push("-g".into());
    }
    // The program links with a big main stack, so main needn't check for one.
    if cfg!(target_vendor = "apple") && !sanitize {
        flags.push("-DTVG_MAIN_STACK=1".into());
    }
    if let Some(sdk) = sysroot {
        flags.push("-isysroot".into());
        flags.push(sdk.into());
    }
    flags
}

/// What every generated C file starts with.
pub const C_PREFIX: &str = "/* Generated by tov. */\n#define _GNU_SOURCE 1\n";

/// What every program's C begins with, the same for all of them (the runtime's interface and
/// codegen's prelude, codegen/prelude.h): precompiled once, a program compiles only what follows.
pub fn fixed_prefix(runtime_h: &str, js_h: &str, prelude: &str) -> String {
    let mut out = String::with_capacity(C_PREFIX.len() + runtime_h.len() + prelude.len() + 128);
    out.push_str(C_PREFIX);
    out.push_str(runtime_h);
    out.push('\n');
    out.push_str("#include <math.h>\n#include <pthread.h>\n#include <stdio.h>\n#include <stdlib.h>\n");
    out.push_str(&js_h.replace("#include \"tov.h\"\n", ""));
    out.push_str(prelude);
    out
}

/// The runtime as one C translation unit: the header pasted in, then each part without its
/// `#include "tov.h"`.
pub fn runtime_source(h: &str, parts: &[&str]) -> String {
    let mut out = String::with_capacity(h.len() + parts.iter().map(|p| p.len()).sum::<usize>() + 64);
    out.push_str(C_PREFIX);
    out.push_str(h);
    out.push('\n');
    for part in parts {
        for line in part.lines() {
            if line.trim_start().starts_with("#include \"tov.h\"") {
                continue;
            }
            out.push_str(line);
            out.push('\n');
        }
    }
    out
}

/// Xcode's clang and the macOS SDK, by xcrun.
pub fn xcrun_toolchain() -> Option<(String, String)> {
    let run = |args: &[&str]| -> Option<String> {
        let out = Command::new("xcrun").args(args).output().ok()?;
        let s = String::from_utf8(out.stdout).ok()?.trim().to_string();
        (out.status.success() && !s.is_empty()).then_some(s)
    };
    let clang = run(&["--find", "clang"])?;
    let sdk = run(&["--show-sdk-path"])?;
    (Path::new(&clang).is_file() && Path::new(&sdk).is_dir()).then_some((clang, sdk))
}

/// The C compiler off macOS (or when xcrun has none): a clang if there is one, else `cc`.
pub fn other_compiler() -> String {
    if cfg!(target_vendor = "apple") && Path::new("/usr/bin/cc").is_file() {
        return "/usr/bin/cc".into();
    }
    for candidate in ["/opt/homebrew/opt/llvm/bin/clang", "/usr/local/opt/llvm/bin/clang"] {
        if Path::new(candidate).is_file() {
            return candidate.to_string();
        }
    }
    // Debian and Ubuntu: the newest of the LLVMs installed side by side (/usr/lib/llvm-<n>), which
    // `clang` on PATH often isn't (x86-64, nbody: 239 ms from clang 19 against 369 from Ubuntu
    // 24.04's default clang 18)
    let newest = std::fs::read_dir("/usr/lib").ok().and_then(|entries| {
        entries
            .flatten()
            .filter_map(|e| e.file_name().to_str()?.strip_prefix("llvm-")?.parse::<u32>().ok())
            .filter(|n| Path::new(&format!("/usr/lib/llvm-{n}/bin/clang")).is_file())
            .max()
    });
    if let Some(n) = newest {
        return format!("/usr/lib/llvm-{n}/bin/clang");
    }
    // Any clang before `cc`, which on Linux is usually GCC: Tov's C runs faster from clang
    // (x86-64, Ubuntu's clang 18 against GCC 13: fib 449 ms against 511, nbody 308 against 382)
    if let Some(path) = std::env::var_os("PATH")
        && let Some(clang) = std::env::split_paths(&path).map(|d| d.join("clang")).find(|p| p.is_file())
    {
        return clang.to_string_lossy().into_owned();
    }
    "cc".into()
}
